// --- عرض الأذكار ---
function renderAdhkar(list) {
  const container = document.getElementById("content");
  container.innerHTML = "";

  list.forEach(item => {

    let current = 0;

    const card = document.createElement("div");
    card.className = "zekr";

    const text = document.createElement("p");
    text.textContent = item.text;
    card.appendChild(text);

    if (item.fadl) {
      const fadl = document.createElement("div");
      fadl.className = "fadl";
      fadl.textContent = item.fadl;
      card.appendChild(fadl);
    }

    const counter = document.createElement("div");
    counter.className = "counter";

    const num = document.createElement("span");
    num.textContent = `0 / ${item.count}`;

    const btn = document.createElement("button");
    btn.textContent = "+";

    btn.onclick = () => {
      if (current < item.count) {
        current++;
        num.textContent = `${current} / ${item.count}`;
      }
    };

    counter.appendChild(num);
    counter.appendChild(btn);
    card.appendChild(counter);

    container.appendChild(card);
  });

  const footer = document.createElement("div");
  footer.textContent = globalFooter;
  footer.style.textAlign = "center";
  footer.style.fontSize = "12px";
  footer.style.color = "#888";
  footer.style.marginTop = "35px";
  footer.style.whiteSpace = "pre-line";

  container.appendChild(footer);
}


